//! `app.icon`: the app's SVG rendered to Android's launcher icon (legacy PNGs plus an adaptive icon) and to iOS's AppIcon set. docs/cli.md, docs/cli-ios.md.

use std::path::Path;

use resvg::{tiny_skia, usvg};

use crate::error::CliError;

/// One launcher density bucket: `mipmap-<name>/`.
#[derive(Debug, PartialEq)]
pub struct Density {
    pub name: &'static str,
    /// Legacy icon size: 48dp at this density.
    pub legacy_px: u32,
}

/// Density → legacy icon size. Adaptive layers are 108dp, `legacy_px * 108 / 48`. To add a density: add a row.
pub const DENSITIES: [Density; 5] = [
    Density {
        name: "mdpi",
        legacy_px: 48,
    },
    Density {
        name: "hdpi",
        legacy_px: 72,
    },
    Density {
        name: "xhdpi",
        legacy_px: 96,
    },
    Density {
        name: "xxhdpi",
        legacy_px: 144,
    },
    Density {
        name: "xxxhdpi",
        legacy_px: 192,
    },
];

impl Density {
    fn adaptive_px(&self) -> u32 {
        self.legacy_px * 108 / 48
    }
}

/// The SVG fills the centre 72dp of the 108dp foreground layer: the part every launcher mask shows. A mark with its
/// own margin (the brand mark sits at 116/160 of its tile) then also stays inside the 66dp safe circle.
const FOREGROUND_SHARE: f32 = 72.0 / 108.0;

/// The adaptive icon: background is a solid colour, foreground the SVG. `mipmap-anydpi-v26` as Android Studio makes it.
const ADAPTIVE_ICON: &str = r#"<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by cargo-parallax from app.icon. Rewritten every run. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"#;

/// Background colour when the SVG's top-left pixel is not opaque (no full-bleed tile).
const NO_TILE_BACKGROUND: [u8; 3] = [0xFF, 0xFF, 0xFF];

/// A parsed `app.icon`, rendered to square PNGs.
struct Icon<'a> {
    tree: usvg::Tree,
    path: &'a Path,
}

impl<'a> Icon<'a> {
    fn read(path: &'a Path) -> Result<Icon<'a>, CliError> {
        let svg = std::fs::read(path).map_err(|source| CliError::IconRead {
            path: path.to_path_buf(),
            source,
        })?;
        Icon::parse(&svg, path)
    }

    fn parse(svg: &[u8], path: &'a Path) -> Result<Icon<'a>, CliError> {
        let tree = usvg::Tree::from_data(svg, &usvg::Options::default())
            .map_err(|e| invalid(path, e.to_string()))?;
        Ok(Icon { tree, path })
    }

    /// The SVG scaled to `share` of a `canvas_px` square, centred, over `background` (transparent if `None`).
    fn render(
        &self,
        canvas_px: u32,
        share: f32,
        background: Option<[u8; 3]>,
    ) -> Result<tiny_skia::Pixmap, CliError> {
        let mut pixmap = tiny_skia::Pixmap::new(canvas_px, canvas_px)
            .ok_or_else(|| invalid(self.path, format!("cannot make a {canvas_px}px canvas")))?;
        if let Some([r, g, b]) = background {
            pixmap.fill(tiny_skia::Color::from_rgba8(r, g, b, 255));
        }
        let size = self.tree.size();
        let scale = canvas_px as f32 * share / size.width().max(size.height());
        let offset = |side: f32| (canvas_px as f32 - side * scale) / 2.0;
        let transform = tiny_skia::Transform::from_row(
            scale,
            0.0,
            0.0,
            scale,
            offset(size.width()),
            offset(size.height()),
        );
        resvg::render(&self.tree, transform, &mut pixmap.as_mut());
        Ok(pixmap)
    }

    fn png(&self, pixmap: tiny_skia::Pixmap) -> Result<Vec<u8>, CliError> {
        pixmap
            .encode_png()
            .map_err(|e| invalid(self.path, e.to_string()))
    }

    /// The SVG's top-left pixel when opaque (a full-bleed tile), else `NO_TILE_BACKGROUND`.
    fn tile_colour(&self) -> Result<[u8; 3], CliError> {
        let corner = self
            .render(DENSITIES[0].legacy_px, 1.0, None)?
            .pixel(0, 0)
            .map(|p| p.demultiply());
        Ok(match corner {
            Some(corner) if corner.alpha() == 255 => [corner.red(), corner.green(), corner.blue()],
            _ => NO_TILE_BACKGROUND,
        })
    }
}

fn invalid(path: &Path, reason: String) -> CliError {
    CliError::IconInvalid {
        path: path.to_path_buf(),
        reason,
    }
}

/// iOS app icons: (file name, PNG) for each (file name, pixel size). Opaque, as the App Store requires: the SVG is
/// drawn over its tile colour.
pub fn app_icon_set(
    svg_path: &Path,
    sizes: &[(String, u32)],
) -> Result<Vec<(String, Vec<u8>)>, CliError> {
    render_app_icons(&Icon::read(svg_path)?, sizes)
}

fn render_app_icons(
    icon: &Icon,
    sizes: &[(String, u32)],
) -> Result<Vec<(String, Vec<u8>)>, CliError> {
    let background = icon.tile_colour()?;
    sizes
        .iter()
        .map(|(name, px)| {
            Ok((
                name.clone(),
                icon.png(icon.render(*px, 1.0, Some(background))?)?,
            ))
        })
        .collect()
}

/// Reads and renders `app.icon`: (path under the Gradle project, file bytes) for every launcher icon file.
pub fn launcher_icon(svg_path: &Path) -> Result<Vec<(String, Vec<u8>)>, CliError> {
    render_icon(&Icon::read(svg_path)?)
}

fn render_icon(icon: &Icon) -> Result<Vec<(String, Vec<u8>)>, CliError> {
    let background = icon.tile_colour()?;
    let mut files = Vec::new();
    for density in &DENSITIES {
        let legacy = icon.render(density.legacy_px, 1.0, None)?;
        let dir = format!("src/main/res/mipmap-{}", density.name);
        files.push((format!("{dir}/ic_launcher.png"), icon.png(legacy)?));
        let foreground = icon.render(density.adaptive_px(), FOREGROUND_SHARE, None)?;
        files.push((
            format!("{dir}/ic_launcher_foreground.png"),
            icon.png(foreground)?,
        ));
    }
    files.push((
        "src/main/res/mipmap-anydpi-v26/ic_launcher.xml".into(),
        ADAPTIVE_ICON.into(),
    ));
    let [r, g, b] = background;
    files.push((
        "src/main/res/values/ic_launcher_background.xml".into(),
        format!(
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by cargo-parallax: app.icon's tile colour. -->\n<resources>\n    <color name=\"ic_launcher_background\">#{r:02X}{g:02X}{b:02X}</color>\n</resources>\n"
        )
        .into_bytes(),
    ));
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn density_table() {
        // (bucket, legacy px, adaptive 108dp px): Android's 1x, 1.5x, 2x, 3x, 4x.
        let cases = [
            ("mdpi", 48, 108),
            ("hdpi", 72, 162),
            ("xhdpi", 96, 216),
            ("xxhdpi", 144, 324),
            ("xxxhdpi", 192, 432),
        ];
        assert_eq!(DENSITIES.len(), cases.len(), "every density row has a case");
        for (density, case) in DENSITIES.iter().zip(cases) {
            assert_eq!(
                (density.name, density.legacy_px, density.adaptive_px()),
                case
            );
        }
    }

    /// Width and height from a PNG's IHDR chunk.
    fn png_size(png: &[u8]) -> (u32, u32) {
        let be = |at: usize| u32::from_be_bytes([png[at], png[at + 1], png[at + 2], png[at + 3]]);
        (be(16), be(20))
    }

    #[test]
    fn render_table() -> Result<(), CliError> {
        let tiled = br##"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"><rect width="10" height="10" fill="#123456"/><rect x="3" y="3" width="4" height="4" fill="#fff"/></svg>"##;
        let untiled = br##"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"><circle cx="5" cy="5" r="3"/></svg>"##;
        // (row name, SVG, expected background colour)
        let cases: [(&str, &[u8], &str); 2] = [
            ("full-bleed tile gives the background", tiled, "#123456"),
            ("no tile falls back to white", untiled, "#FFFFFF"),
        ];
        for (name, svg, colour) in cases {
            let files = render_icon(&Icon::parse(svg, Path::new("icon.svg"))?)?;
            let file = |path: &str| {
                files
                    .iter()
                    .find(|(p, _)| p == path)
                    .map(|(_, bytes)| bytes.as_slice())
            };
            for d in &DENSITIES {
                let dir = format!("src/main/res/mipmap-{}", d.name);
                let (legacy, adaptive) = (d.legacy_px, d.adaptive_px());
                assert_eq!(
                    file(&format!("{dir}/ic_launcher.png")).map(png_size),
                    Some((legacy, legacy)),
                    "{name} {}",
                    d.name
                );
                assert_eq!(
                    file(&format!("{dir}/ic_launcher_foreground.png")).map(png_size),
                    Some((adaptive, adaptive)),
                    "{name} {} foreground",
                    d.name
                );
            }
            assert_eq!(
                file("src/main/res/mipmap-anydpi-v26/ic_launcher.xml"),
                Some(ADAPTIVE_ICON.as_bytes()),
                "{name}"
            );
            let values = file("src/main/res/values/ic_launcher_background.xml")
                .map(|v| String::from_utf8_lossy(v).into_owned())
                .unwrap_or_default();
            assert!(values.contains(&format!(">{colour}<")), "{name}: {values}");
            assert_eq!(files.len(), DENSITIES.len() * 2 + 2, "{name}: file count");
        }
        Ok(())
    }

    #[test]
    fn app_icon_table() -> Result<(), CliError> {
        let tiled = br##"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"><rect width="10" height="10" fill="#123456"/></svg>"##;
        let untiled = br##"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 10 10"><circle cx="5" cy="5" r="3"/></svg>"##;
        let sizes = [("a@2x.png".to_string(), 40), ("b.png".to_string(), 167)];
        // (row name, SVG, expected top-left pixel): every icon is opaque, its corner the tile colour or white.
        let cases: [(&str, &[u8], [u8; 4]); 2] = [
            ("tile colour shows", tiled, [0x12, 0x34, 0x56, 255]),
            ("no tile is drawn over white", untiled, [255, 255, 255, 255]),
        ];
        for (name, svg, corner) in cases {
            let files = render_app_icons(&Icon::parse(svg, Path::new("icon.svg"))?, &sizes)?;
            let got: Vec<_> = files
                .iter()
                .map(|(file, png)| {
                    let pixel = tiny_skia::Pixmap::decode_png(png)
                        .ok()
                        .and_then(|p| p.pixel(0, 0))
                        .map(|p| [p.red(), p.green(), p.blue(), p.alpha()]);
                    (file.as_str(), png_size(png), pixel)
                })
                .collect();
            let want = vec![
                ("a@2x.png", (40, 40), Some(corner)),
                ("b.png", (167, 167), Some(corner)),
            ];
            assert_eq!(got, want, "{name}");
        }
        Ok(())
    }

    #[test]
    fn error_table() {
        // (row name, path, SVG bytes or None to read the path, expected variant). Every message names the path.
        let cases: [(&str, &str, Option<&[u8]>, &str); 3] = [
            ("missing file", "/no/such/dir/icon.svg", None, "IconRead"),
            ("not SVG", "icon.svg", Some(b"PNG, not SVG"), "IconInvalid"),
            ("not XML", "icon.svg", Some(b"<svg"), "IconInvalid"),
        ];
        for (name, path, svg, want) in cases {
            let got = match svg {
                Some(svg) => Icon::parse(svg, Path::new(path)).and_then(|icon| render_icon(&icon)),
                None => launcher_icon(Path::new(path)),
            }
            .map(|_| ())
            .map_err(|e| (e.variant(), e.to_string().contains(path)));
            assert_eq!(got, Err((want.to_string(), true)), "{name}");
        }
    }
}
